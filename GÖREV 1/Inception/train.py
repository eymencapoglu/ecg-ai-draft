# DÜZELTME BURADA: 'verbose=True' kaldırıldı.
scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='max', patience=3, factor=0.5)

# --- 4. EĞİTİM DÖNGÜSÜ ---
best_f1 = 0.0
print(f"\nEğitim Başlıyor... Kayıt Yeri: {MODEL_SAVE_DIR}")

for epoch in range(EPOCHS):
    model.train()
    running_loss = 0.0
    
    loop = tqdm(train_loader, desc=f"Epoch {epoch+1}")
    for inputs, targets in loop:
        inputs, targets = inputs.to(DEVICE), targets.to(DEVICE)
        
        # Normalizasyon
        mean = inputs.mean(dim=2, keepdim=True)
        std = inputs.std(dim=2, keepdim=True)
        inputs = (inputs - mean) / (std + 1e-5)
        
        optimizer.zero_grad()
        outputs = model(inputs)
        loss = criterion(outputs, targets)
        loss.backward()
        
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()
        
        running_loss += loss.item()
        loop.set_postfix(loss=loss.item())

    # Validation
    model.eval()
    all_preds, all_targets = [], []
    with torch.no_grad():
        for inputs, targets in val_loader:
            inputs, targets = inputs.to(DEVICE), targets.to(DEVICE)
            mean = inputs.mean(dim=2, keepdim=True)
            std = inputs.std(dim=2, keepdim=True)
            inputs = (inputs - mean) / (std + 1e-5)
            outputs = model(inputs)
            _, preds = torch.max(outputs, 1)
            all_preds.extend(preds.cpu().numpy())
            all_targets.extend(targets.cpu().numpy())
            
    val_f1 = f1_score(all_targets, all_preds, average='macro')
    val_acc = accuracy_score(all_targets, all_preds)
    
    # LR değerini manuel olarak yazdırıyoruz
    current_lr = optimizer.param_groups[0]['lr']
    print(f"Epoch {epoch+1} -> Val Macro F1: {val_f1:.4f} | Acc: {val_acc:.4f} | LR: {current_lr}")
    
    scheduler.step(val_f1)
    
    # Kayıt (Inception klasörüne)
    torch.save(model.state_dict(), os.path.join(MODEL_SAVE_DIR, f"model_epoch_{epoch+1}.pth"))
    
    if val_f1 > best_f1:
        best_f1 = val_f1
