# --- 1. MODEL MİMARİSİ (CNN + Bi-LSTM + Attention) ---

class Attention(nn.Module):
    def __init__(self, hidden_dim):
        super(Attention, self).__init__()
        self.query_layer = nn.Linear(hidden_dim, 256)
        self.value_layer = nn.Linear(hidden_dim, 256)
        self.v = nn.Linear(256, 1, bias=False)

    def forward(self, x):
        # x: (Batch, Time, Hidden)
        q = torch.tanh(self.query_layer(x)) 
        scores = self.v(q)                  
        weights = F.softmax(scores, dim=1)  
        return x * weights 

class TeknofestAttentionModel(nn.Module):
    def __init__(self, num_classes):
        super(TeknofestAttentionModel, self).__init__()
        
        # CNN (Conv1D)
        self.conv1 = nn.Conv1d(in_channels=12, out_channels=128, kernel_size=7, padding=3)
        self.bn1 = nn.BatchNorm1d(128)
        self.relu = nn.ReLU()
        
        # Bi-LSTM
        self.lstm = nn.LSTM(input_size=128, hidden_size=128, num_layers=1, 
                            batch_first=True, bidirectional=True)
        
        # Attention
        self.attention = Attention(hidden_dim=256)
        
        # Classifier
        self.fc1 = nn.Linear(512, 256) # 256 (Avg) + 256 (Max) = 512
        self.dropout = nn.Dropout(0.4)
        self.fc_out = nn.Linear(256, num_classes)

    def forward(self, x):
        # x: (Batch, 12, 5000)
        
        # CNN
        x = self.conv1(x)      
        x = self.bn1(x)
        x = self.relu(x)
        
        # LSTM Hazırlık (Batch, Feat, Time) -> (Batch, Time, Feat)
        x = x.permute(0, 2, 1) 
        
        # LSTM
        x, _ = self.lstm(x)    
        
        # Attention
        x = self.attention(x)  
        
        # Global Pooling (Avg + Max)
        avg_pool = torch.mean(x, dim=1) 
        max_pool, _ = torch.max(x, dim=1)  
        
        combined = torch.cat([avg_pool, max_pool], dim=1) 
        
        # Sınıflandırma
        x = self.fc1(combined)
        x = self.relu(x)
        x = self.dropout(x)
        x = self.fc_out(x)
        
        return x

# --- 2. VERİ YÜKLEME ---
def load_dataset_from_parts(folder_path, prefix):
    files = glob.glob(os.path.join(folder_path, f"{prefix}*.pt"))
    datasets = []
    print(f"Konum taranıyor: {folder_path} -> {len(files)} parça.")
    for f in tqdm(files):
        try:
            data = torch.load(f)
            if torch.isnan(data['X']).any(): data['X'] = torch.nan_to_num(data['X'], nan=0.0)
            if len(data['y']) > 0: datasets.append(TensorDataset(data['X'], data['y']))
        except: pass
    return ConcatDataset(datasets)

